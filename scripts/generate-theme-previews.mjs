import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { themePresets } from "../src/theme-presets.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const output = path.join(root, "docs", "theme-previews");
const escapeXml = (value) => String(value)
  .replaceAll("&", "&amp;")
  .replaceAll("<", "&lt;")
  .replaceAll(">", "&gt;")
  .replaceAll('"', "&quot;");

await mkdir(output, { recursive: true });
for (const [id, theme] of Object.entries(themePresets)) {
  const token = (name) => escapeXml(theme.variables[name]);
  const svg = `<!-- Generated by npm run themes:previews. -->
<svg xmlns="http://www.w3.org/2000/svg" width="480" height="270" viewBox="0 0 480 270" role="img" aria-labelledby="title description">
  <title id="title">${escapeXml(theme.label)} presentation theme preview</title>
  <desc id="description">A sample title slide and cards using the ${escapeXml(theme.label)} color palette.</desc>
  <rect width="480" height="270" rx="12" fill="${token("--harness-bg")}"/>
  <circle cx="422" cy="38" r="92" fill="${token("--harness-accent")}" opacity="0.12"/>
  <rect x="32" y="30" width="42" height="5" rx="2.5" fill="${token("--harness-accent")}"/>
  <text x="32" y="63" fill="${token("--harness-accent")}" font-family="Arial, sans-serif" font-size="11" font-weight="700" letter-spacing="2">PRESENTATION</text>
  <text x="32" y="111" fill="${token("--harness-heading")}" font-family="Arial, sans-serif" font-size="36" font-weight="700">${escapeXml(theme.label)}</text>
  <text x="32" y="137" fill="${token("--harness-muted")}" font-family="Arial, sans-serif" font-size="15">A focused theme for clear ideas.</text>
  <g transform="translate(32 169)">
    <rect width="126" height="67" rx="${id === "mono" ? 0 : 10}" fill="${token("--harness-panel")}" stroke="${token("--harness-muted")}" stroke-opacity="0.35"/>
    <rect x="16" y="16" width="38" height="4" rx="2" fill="${token("--harness-accent")}"/>
    <rect x="16" y="31" width="82" height="5" rx="2.5" fill="${token("--harness-text")}" opacity="0.85"/>
    <rect x="16" y="45" width="62" height="4" rx="2" fill="${token("--harness-muted")}" opacity="0.75"/>
  </g>
  <g transform="translate(169 169)">
    <rect width="126" height="67" rx="${id === "mono" ? 0 : 10}" fill="${token("--harness-panel")}" stroke="${token("--harness-muted")}" stroke-opacity="0.35"/>
    <rect x="16" y="16" width="38" height="4" rx="2" fill="${token("--harness-accent")}"/>
    <rect x="16" y="31" width="72" height="5" rx="2.5" fill="${token("--harness-text")}" opacity="0.85"/>
    <rect x="16" y="45" width="88" height="4" rx="2" fill="${token("--harness-muted")}" opacity="0.75"/>
  </g>
  <g transform="translate(306 169)">
    <rect width="126" height="67" rx="${id === "mono" ? 0 : 10}" fill="${token("--harness-panel")}" stroke="${token("--harness-muted")}" stroke-opacity="0.35"/>
    <rect x="16" y="16" width="38" height="4" rx="2" fill="${token("--harness-accent")}"/>
    <rect x="16" y="31" width="80" height="5" rx="2.5" fill="${token("--harness-text")}" opacity="0.85"/>
    <rect x="16" y="45" width="54" height="4" rx="2" fill="${token("--harness-muted")}" opacity="0.75"/>
  </g>
  <rect x="32" y="257" width="416" height="3" rx="1.5" fill="${token("--harness-accent")}"/>
</svg>
`;
  await writeFile(path.join(output, `${id}.svg`), svg);
}

console.log(`Generated ${Object.keys(themePresets).length} theme previews in ${path.relative(root, output)}`);
